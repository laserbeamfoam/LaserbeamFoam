def overlap(lo, hi, a, b):
    """fraction of the cell [lo, hi] inside [a, b]"""
    return max(0.0, min(hi, b) - max(lo, a)) / (hi - lo)


def stefan_boiling():
    """17: film boiling. The wall at Tsat + 50 K heats a vapour film that evaporates a 10 um liquid slab
    and pushes it out; vapour at Tsat and 1 bar beyond the slab, open end. Starts from the similarity
    solution at t0 = 100 us and runs to 400 us (the film grows from 65 to 130 um). The vapour
    conductivity is raised 100x (Pr 0.0067) to make it quick; the reference scales with it.
    - The slab's conductivity is lowered 100x (Pr 16): the slab is only a piston, and the 0.1-0.3 K
      Hertz-Knudsen superheat of its inner surface must not reach the outer one, which then evaporates
      into the saturated vapour too (with Fe's own conductivity it took a third of the evaporation).
    - A thick liquid column flowing out of the open end instead rings on the vapour film and heats it.
    - At t0 the decelerating slab sets the film 0.11 kPa below 1 bar (Tsat -0.27 K) and Hertz-Knudsen
      needs +0.29 K: < 0.1 % of the 50 K, later less
    - The interface cell's one temperature still hands that superheat to the liquid passing through it
      as the slab moves: the slab warms ~50 mK and takes ~3 % of the heat (the same on 400 cells, at
      dt/4, and with the slab's conductivity lowered another 100x). The reference keeps its liquid at
      Tsat, so the check balances the energy (evaporation + the slab's warming) against the heat the
      similarity solution conducts, rather than the evaporated mass alone"""
    N, L = 200, 200e-6
    dx = L / N
    x = cells(N, L)
    Tsat, dT, t0, H = 3134.0, 50.0, 1e-4, 10e-6
    Tw = Tsat + dT
    vapPr, liqPr = 0.0067, 16.0
    cpv = CP_FEV
    kv = 1.0e-5 * cpv / vapPr
    rv = 1e5 * M_FE / (8314.47 * Tsat)                  # vapour density at Tsat, 1 bar
    al = kv / (rv * cpv)
    St = cpv * dT / 6.09e6
    lo, hi = 1e-9, 5.0
    for _ in range(200):
        lam = 0.5 * (lo + hi)
        g = lam * math.exp(lam * lam) * math.erf(lam) - St / math.sqrt(math.pi)
        lo, hi = (lam, hi) if g < 0 else (lo, lam)
    d0 = 2 * lam * math.sqrt(al * t0)
    u0 = d0 / (2 * t0)                                   # slab speed: d(delta)/dt
    cond = [overlap(xi - 0.5 * dx, xi + 0.5 * dx, d0, d0 + H) for xi in x]
    vap = [1.0 - c for c in cond]
    T = [Tw - dT * math.erf(xi / (2 * math.sqrt(al * t0))) / math.erf(lam) if xi < d0 else Tsat for xi in x]
    U = [0.0 if (xi + 0.5 * dx <= d0) else u0 for xi in x]
    f = {"T": T, "p": [1e5] * N, "U": U, "alpha.metal1": cond, "alpha.metal1vapour": vap,
         "alpha.argon": [0.0] * N}
    return make_case("17_stefanBoiling", N=N, L=L, gas="argon", left=wall_at(Tw), right=open_vapour(Tsat),
                     fields=f, endTime=3e-4, writeInterval=2.5e-5, maxDeltaT=1e-7, vapourPr=vapPr, liquidPr=liqPr,
                     meta=dict(Tw=Tw, Tsat=Tsat, t0=t0, H=H, delta0=d0, lam=lam, alpha_v=al, k_v=kv, rho_v=rv,
                               cp_v=cpv, u0=u0, p_inf=1e5, c_l=800.0, rho_l=7030.0, L_v=6.09e6),
                     notes="film boiling (Welch & Wilson 2000): a vapour film between a wall at Tsat + 50 K and "
                           "a 10 um liquid slab grows as 2 lam sqrt(alpha_v t); started from the similarity "
                           "solution at t0 = 100 us (vapour conductivity raised 100x, slab's lowered 100x)")


def stefan_condensation():
    """18: saturated Fe vapour (1 bar, Tsat) condenses onto liquid Fe 100 K below Tsat, 60 um deep on a
    wall held at that temperature. Hertz-Knudsen limits the rate, the latent heat warms the surface,
    and the rate falls (20.8 -> 14.0 kg/m2/s in 20 us): the reference solves the half-space conduction
    with the same Hertz-Knudsen law at the surface (tools/stefan_lv.py). Real conductivities"""
    N, L = 200, 100e-6
    dx = L / N
    x = cells(N, L)
    Tsat, T0 = 3134.0, 3034.0
    h_l = 60.25e-6                                       # mid-cell surface
    cond = [min(max((h_l - (xi - 0.5 * dx)) / dx, 0.0), 1.0) for xi in x]
    vap = [1.0 - c for c in cond]
    T = [T0 if c > 0 else Tsat for c in cond]
    f = {"T": T, "p": [1e5] * N, "U": [0.0] * N, "alpha.metal1": cond, "alpha.metal1vapour": vap,
         "alpha.argon": [0.0] * N}
    kl = 6.0e-3 * 800 / 0.16
    return make_case("18_stefanCondensation", N=N, L=L, gas="argon", left=wall_at(T0), right=open_vapour(Tsat),
                     fields=f, endTime=2e-5, writeInterval=1e-6, maxDeltaT=1e-8,
                     meta=dict(T0=T0, Tsat=Tsat, h_l=h_l, p_inf=1e5, k_l=kl, rho_l=7030.0, c_l=800.0,
                               cp_v=CP_FEV, sigma_c=1.0),
                     notes="condensation of saturated Fe vapour onto liquid Fe 100 K below Tsat: Hertz-Knudsen "
                           "at the surface against half-space conduction (Duhamel), real conductivities")


# ----------------------------------------------------------------------------- 2D thermocapillary layer
def thermocapillary_layer():
    """19: a 20 um liquid Fe layer on a no-slip wall under 20 um of argon (slip lid), periodic along
    the surface with T = T0 + G*y (fixedJump), no gravity, no phase change. Steady state: plane
    Couette flow driven by the Marangoni stress tau = dsigma/dT*G, so mu_l*du/dx = tau in the liquid,
    the surface moves at tau*h/mu_l, and the argon rides along at that speed (no shear under a slip lid)"""
    Nx, Ny, dx = 40, 4, 1e-6
    L, Ly = Nx * dx, Ny * dx
    h, T0, G, dsdT = 20e-6, 1800.0, 1e5, -4e-4
    x = cells(Nx, L)
    cond = [1.0 if xi < h else 0.0 for xi in x]
    f = {"T": [T0] * Nx, "p": [1e5] * Nx, "U": [0.0] * Nx, "alpha.metal1": cond,
         "alpha.metal1vapour": [0.0] * Nx, "alpha.argon": [1.0 - c for c in cond]}
    top = {"_type": "wall", "U": "type slip;", "p_rgh": "type fixedFluxPressure; value $internalField;",
           "p": "type calculated; value $internalField;", "Laser_boundary": "type fixedValue; value uniform -1;"}
    name = "19_thermocapillaryLayer"
    case = make_case(name, N=Nx, L=L, gas="argon", left="wall", right=top, fields=f,
                     endTime=1.5e-3, writeInterval=1e-4, maxDeltaT=5e-8,
                     meta=dict(Nx=Nx, Ny=Ny, h=h, T0=T0, G=G, dsigmadT=dsdT, mu_l=6.0e-3,
                               tau=dsdT * G, u_s=dsdT * G * h / 6.0e-3),
                     notes="thermocapillary Couette layer: tangential stress balance mu*du/dn = dsigma/dT*dT/ds")
    # no phase change, Marangoni on: dsigma/dT on both liquid-gas pairs
    tp = os.path.join(case, "constant/thermophysicalProperties")
    s = open(tp).read()
    s = s.replace("accommodationCoeffEvap  1.0;", "accommodationCoeffEvap  0.0;")
    s = s.replace("accommodationCoeffCond  1.0;", "accommodationCoeffCond  0.0;")
    s = s.replace("(metal1vapour metal1)   0.0\n    (argon metal1)          0.0",
                  f"(metal1vapour metal1)   {dsdT!r}\n    (argon metal1)          {dsdT!r}", 1)
    # sigma only acts through curvature (none here): 0.05 N/m keeps dt = 5e-8 s under the capillary
    # limit sqrt(rho*dx^3/(2*pi*sigma)) (Brackbill et al. 1992), which 1.8 N/m would cut to 1.8e-8 s
    s = s.replace("(metal1vapour metal1)   1.8\n    (argon metal1)          1.8",
                  "(metal1vapour metal1)   0.05\n    (argon metal1)          0.05", 1)
    open(tp, "w").write(s)
    # 2D mesh: x across the layer (wall | slip lid), y along it (cyclic, T jumps by G*Ly), z empty
    write(case, "system/blockMeshDict", "dictionary", f"""scale   1;

vertices
(
    (0 0 0) ({L!r} 0 0) ({L!r} {Ly!r} 0) (0 {Ly!r} 0)
    (0 0 {dx!r}) ({L!r} 0 {dx!r}) ({L!r} {Ly!r} {dx!r}) (0 {Ly!r} {dx!r})
);

blocks ( hex (0 1 2 3 4 5 6 7) ({Nx} {Ny} 1) simpleGrading (1 1 1) );

boundary
(
    left  {{ type wall; faces ((0 4 7 3)); }}
    right {{ type wall; faces ((1 2 6 5)); }}
    ylo   {{ type cyclic; neighbourPatch yhi; faces ((0 1 5 4)); }}
    yhi   {{ type cyclic; neighbourPatch ylo; faces ((3 7 6 2)); }}
    frontAndBack {{ type empty; faces ((0 3 2 1) (4 5 6 7)); }}
);
""")
    # fields on the Nx*Ny cells, blockMesh order: x fastest
    yc = [(j + 0.5) * dx for j in range(Ny)]
    walls = {"U": ("type fixedValue; value uniform (0 0 0);", "type slip;"),
             "T": ("type zeroGradient;", "type zeroGradient;"),
             "p_rgh": ("type fixedFluxPressure; value uniform 1e5;", "type fixedFluxPressure; value uniform 1e5;"),
             "p": ("type calculated; value uniform 1e5;", "type calculated; value uniform 1e5;"),
             "Laser_boundary": ("type fixedValue; value uniform -1;", "type fixedValue; value uniform -1;")}
    def field(fname, vals, dims, vector=False):
        cls = "volVectorField" if vector else "volScalarField"
        if vector:
            body = "nonuniform List<vector>\n{}\n(\n{}\n)".format(len(vals), "\n".join(f"(0 {v!r} 0)" for v in vals))
        else:
            body = "nonuniform List<scalar>\n{}\n(\n{}\n)".format(len(vals), "\n".join(repr(float(v)) for v in vals))
        lw, rw = walls.get(fname, ("type zeroGradient;", "type zeroGradient;"))
        if fname == "T":
            cyc = (f"ylo {{ type fixedJump; patchType cyclic; jump uniform {G * Ly!r}; value uniform {T0!r}; }}\n"
                   f"    yhi {{ type fixedJump; patchType cyclic; value uniform {T0!r}; }}")
        else:
            cyc = "ylo { type cyclic; }\n    yhi { type cyclic; }"
        write(case, f"0/{fname}", cls, f"""dimensions      {dims};

internalField   {body};

boundaryField
{{
    left         {{ {lw} }}
    right        {{ {rw} }}
    {cyc}
    frontAndBack {{ type empty; }}
}}
""")
    grid = [(i, j) for j in range(Ny) for i in range(Nx)]
    field("T", [T0 + G * yc[j] for i, j in grid], "[0 0 0 1 0 0 0]")
    field("p", [1e5] * len(grid), "[1 -1 -2 0 0 0 0]")
    field("p_rgh", [1e5] * len(grid), "[1 -1 -2 0 0 0 0]")
    field("U", [0.0] * len(grid), "[0 1 -1 0 0 0 0]", vector=True)
    for ph in ("metal1", "metal1vapour", "argon"):
        v = {"metal1": cond, "metal1vapour": [0.0] * Nx, "argon": [1.0 - c for c in cond]}[ph]
        field(f"alpha.{ph}", [v[i] for i, j in grid], "[0 0 0 0 0 0 0]")
    field("Laser_boundary", [0.0] * len(grid), "[0 0 0 0 0 0 0]")
    return case


