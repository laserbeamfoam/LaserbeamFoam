#!/usr/bin/env python3
"""
Generate the 1D verification cases for compressibleLaserbeamFoam.

Every case is a 1D column of cubic cells (the two transverse directions are one cell
of the same size and 'empty'), except 19, a 2D layer periodic along its surface.

Fields are written directly (nonuniform lists), no setFields needed.
Usage: python3 gen_cases.py [outdir]
"""
import json
import math
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "cases"
RU = 8.314                      # the solver's gas constant
HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
  compressibleLaserbeamFoam verification suite (generated by gen_cases.py)
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    location    "{loc}";
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def write(case, rel, cls, body):
    path = os.path.join(case, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    loc, obj = os.path.dirname(rel), os.path.basename(rel)
    with open(path, "w") as f:
        f.write(HDR.format(cls=cls, loc=loc, obj=obj) + body +
                "\n// ************************************************************************* //\n")


# ----------------------------------------------------------------------------- materials
# name: (phaseState, thermo block, transport, extra keys)
